BEGIN;

CREATE SCHEMA IF NOT EXISTS dipcheese;
SET search_path TO dipcheese, public;
SET client_encoding TO 'UTF8';

-- ---------------------------------------------------------------------------
-- 1. Socios, capital y organización
-- ---------------------------------------------------------------------------

CREATE TABLE socio (
    id                 smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             text NOT NULL,
    apellido           text NOT NULL,
    participacion_pct  numeric(5,2) NOT NULL
                       CHECK (participacion_pct > 0 AND participacion_pct <= 100),
    UNIQUE (nombre, apellido)
);

COMMENT ON TABLE socio IS 'Socios de la SAS. El informe fija 5 socios con 20% cada uno.';

CREATE TABLE aporte_capital (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id    smallint REFERENCES socio(id),
    fecha       date NOT NULL,
    monto       numeric(14,2) NOT NULL CHECK (monto > 0),
    tipo        text NOT NULL CHECK (tipo IN ('inicial', 'ampliacion')),
    medio_pago  text NOT NULL
                CHECK (medio_pago IN ('efectivo', 'transferencia_mp', 'transferencia_naranja', 'otro')),
    nota        text,
    -- Los aportes iniciales son individuales; una ampliación puede registrarse
    -- como total agregado cuando el informe no discrimina por socio.
    CHECK (tipo = 'ampliacion' OR socio_id IS NOT NULL)
);

CREATE UNIQUE INDEX ux_aporte_inicial_por_socio
    ON aporte_capital (socio_id)
    WHERE tipo = 'inicial';

COMMENT ON TABLE aporte_capital IS
    'Aportes de capital. El informe solo detalla los $68.187 iniciales por socio; '
    'la diferencia hasta el capital social final ($1.160.938) se registra como ampliación agregada.';

CREATE TABLE rol (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       text NOT NULL UNIQUE,
    descripcion  text
);

CREATE TABLE socio_rol (
    socio_id  smallint NOT NULL REFERENCES socio(id),
    rol_id    smallint NOT NULL REFERENCES rol(id),
    desde     date NOT NULL,
    hasta     date,
    PRIMARY KEY (socio_id, rol_id, desde),
    CHECK (hasta IS NULL OR hasta >= desde)
);

COMMENT ON TABLE socio_rol IS
    'Asignación de áreas. El informe solo identifica a Jeremías García en Recursos Humanos; '
    'el resto del organigrama está en los anexos y no se transcribe aquí.';

-- ---------------------------------------------------------------------------
-- 2. Catálogo de productos y precios
-- ---------------------------------------------------------------------------

CREATE TABLE categoria_producto (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  text NOT NULL UNIQUE
);

CREATE TABLE producto (
    id            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        text NOT NULL UNIQUE,
    nombre        text NOT NULL,
    categoria_id  smallint NOT NULL REFERENCES categoria_producto(id),
    unidad_venta  text NOT NULL
                  CHECK (unidad_venta IN ('porcion', 'bandeja', 'docena', 'unidad', 'combo')),
    es_congelado  boolean NOT NULL DEFAULT false,
    activo        boolean NOT NULL DEFAULT true
);

CREATE TABLE producto_precio (
    id             smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    smallint NOT NULL REFERENCES producto(id),
    vigente_desde  date NOT NULL,
    vigente_hasta  date,
    precio         numeric(12,2) NOT NULL CHECK (precio >= 0),
    moneda         char(3) NOT NULL DEFAULT 'ARS',
    nota           text,
    CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    UNIQUE (producto_id, vigente_desde)
);

CREATE TABLE producto_costo (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     smallint NOT NULL REFERENCES producto(id),
    vigente_desde   date NOT NULL,
    vigente_hasta   date,
    costo_unitario  numeric(12,2) NOT NULL CHECK (costo_unitario >= 0),
    nota            text,
    CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    UNIQUE (producto_id, vigente_desde)
);

COMMENT ON TABLE producto_costo IS
    'Costos unitarios por producto y período (mayo-junio / agosto-octubre). '
    'El informe presenta esta información en figuras; los valores no están en el texto.';

-- ---------------------------------------------------------------------------
-- 3. Insumos, proveedores y compras
-- ---------------------------------------------------------------------------

CREATE TABLE insumo (
    id             smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         text NOT NULL UNIQUE,
    unidad_medida  text NOT NULL,
    perecedero     boolean NOT NULL DEFAULT false
);

CREATE TABLE proveedor (
    id                 smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             text NOT NULL UNIQUE,
    tipo               text NOT NULL CHECK (tipo IN ('principal', 'alternativo')),
    direccion          text,
    condiciones_pago   text,
    frecuencia_compra  text,
    notas              text
);

CREATE TABLE proveedor_insumo (
    id                  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id        smallint NOT NULL REFERENCES proveedor(id),
    insumo_id           smallint NOT NULL REFERENCES insumo(id),
    unidad_compra       text NOT NULL,
    precio_unitario     numeric(12,2) CHECK (precio_unitario >= 0),
    minimo_compra       numeric(10,2) CHECK (minimo_compra >= 0),
    descuento_unitario  numeric(12,2) CHECK (descuento_unitario >= 0),
    UNIQUE (proveedor_id, insumo_id)
);

CREATE TABLE compra (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id smallint NOT NULL REFERENCES proveedor(id),
    fecha        date NOT NULL,
    medio_pago   text NOT NULL
                 CHECK (medio_pago IN ('efectivo', 'transferencia_mp', 'transferencia_naranja', 'otro')),
    total        numeric(14,2) NOT NULL CHECK (total >= 0),
    nota         text
);

CREATE TABLE detalle_compra (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id       smallint NOT NULL REFERENCES compra(id) ON DELETE CASCADE,
    insumo_id       smallint NOT NULL REFERENCES insumo(id),
    cantidad        numeric(12,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(12,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal        numeric(14,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED
);

COMMENT ON TABLE compra IS
    'El informe no publica facturas ni el detalle de cada compra: la tabla queda '
    'preparada para registrarlas, sin datos inventados.';

-- ---------------------------------------------------------------------------
-- 4. Producción
-- ---------------------------------------------------------------------------

CREATE TABLE costo_fijo (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  text NOT NULL UNIQUE,
    monto   numeric(14,2) NOT NULL CHECK (monto >= 0),
    base    text NOT NULL CHECK (base IN ('jornada', 'mensual', 'unico')),
    nota    text
);

CREATE TABLE jornada_produccion (
    id               smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha            date NOT NULL,
    tandas           smallint NOT NULL CHECK (tandas > 0),
    costo_mano_obra  numeric(14,2) NOT NULL DEFAULT 0 CHECK (costo_mano_obra >= 0),
    costo_insumos    numeric(14,2) CHECK (costo_insumos >= 0),
    nota             text
);

CREATE TABLE lote_produccion (
    id                  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jornada_id          smallint NOT NULL REFERENCES jornada_produccion(id) ON DELETE CASCADE,
    producto_id         smallint NOT NULL REFERENCES producto(id),
    tandas              smallint NOT NULL CHECK (tandas > 0),
    unidades_por_tanda  smallint NOT NULL CHECK (unidades_por_tanda > 0),
    unidades            numeric(12,0) GENERATED ALWAYS AS
                        (tandas::numeric * unidades_por_tanda) STORED
);

COMMENT ON TABLE jornada_produccion IS
    'El informe describe una jornada tipo de 10 tandas; cada tanda rinde 6 bolsas '
    'de 6 chipás (36 unidades), es decir 30 docenas por jornada.';

-- ---------------------------------------------------------------------------
-- 5. Ventas
-- ---------------------------------------------------------------------------

CREATE TABLE evento (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  text NOT NULL,
    fecha   date NOT NULL,
    tipo    text NOT NULL CHECK (tipo IN ('acto', 'feria', 'otro')),
    lugar   text
);

CREATE TABLE venta (
    id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha      date NOT NULL,
    canal      text NOT NULL
               CHECK (canal IN ('acto', 'encargo_congelado', 'mostrador', 'no_discriminado')),
    evento_id  smallint REFERENCES evento(id),
    medio_pago text NOT NULL
               CHECK (medio_pago IN ('efectivo', 'transferencia_mp', 'transferencia_naranja', 'indistinto')),
    total      numeric(14,2) NOT NULL CHECK (total >= 0),
    unidades   integer CHECK (unidades >= 0),
    nota       text,
    CHECK (canal = 'acto' OR evento_id IS NULL)
);

CREATE TABLE detalle_venta (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        smallint NOT NULL REFERENCES venta(id) ON DELETE CASCADE,
    producto_id     smallint NOT NULL REFERENCES producto(id),
    cantidad        integer NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(12,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal        numeric(14,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED
);

COMMENT ON TABLE detalle_venta IS
    'El informe solo publica totales por acto y por canal, no el mix vendido. '
    'La tabla queda preparada para el detalle; las ventas se cargan a nivel total.';

-- ---------------------------------------------------------------------------
-- 6. Punto de equilibrio
-- ---------------------------------------------------------------------------

CREATE TABLE punto_equilibrio_mensual (
    id                    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio                  smallint NOT NULL,
    mes                   smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    unidades_vendidas     integer NOT NULL CHECK (unidades_vendidas >= 0),
    unidades_equilibrio   integer NOT NULL CHECK (unidades_equilibrio >= 0),
    resultado_reportado   integer NOT NULL,
    UNIQUE (anio, mes)
);

COMMENT ON COLUMN punto_equilibrio_mensual.resultado_reportado IS
    'Valor tal como figura en el informe. Se conserva para poder contrastarlo '
    'con el cálculo (vendidas - equilibrio) y detectar diferencias.';

-- ---------------------------------------------------------------------------
-- 7. Estados contables
-- ---------------------------------------------------------------------------

CREATE TABLE estado_resultado_concepto (
    id        smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    text NOT NULL UNIQUE,
    concepto  text NOT NULL,
    tipo      text NOT NULL CHECK (tipo IN ('ingreso', 'costo', 'gasto')),
    monto     numeric(14,2) NOT NULL CHECK (monto >= 0),
    orden     smallint NOT NULL DEFAULT 0,
    nota      text
);

CREATE TABLE estado_patrimonial_rubro (
    id       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo     text NOT NULL
             CHECK (tipo IN ('activo_corriente', 'activo_no_corriente', 'pasivo', 'patrimonio_neto')),
    rubro    text NOT NULL,
    importe  numeric(14,2) NOT NULL CHECK (importe >= 0),
    orden    smallint NOT NULL DEFAULT 0,
    UNIQUE (tipo, rubro)
);

-- ---------------------------------------------------------------------------
-- 8. Objetivos, finanzas y distribución de ganancias
-- ---------------------------------------------------------------------------

CREATE TABLE objetivo (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion  text NOT NULL,
    metrica      text,
    meta_min     numeric(14,2) CHECK (meta_min >= 0),
    meta_max     numeric(14,2) CHECK (meta_max >= 0),
    unidad       text,
    resultado    numeric(14,2),
    estado       text NOT NULL CHECK (estado IN ('cumplido', 'no_cumplido', 'sin_medicion')),
    nota         text,
    CHECK (meta_max IS NULL OR meta_min IS NULL OR meta_max >= meta_min)
);

CREATE TABLE billetera_virtual (
    id                      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  text NOT NULL UNIQUE,
    rendimiento_mensual_pct numeric(5,2) NOT NULL CHECK (rendimiento_mensual_pct >= 0)
);

CREATE TABLE rendimiento_financiero (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billetera_id smallint REFERENCES billetera_virtual(id),
    periodo      text NOT NULL,
    monto        numeric(12,2) NOT NULL CHECK (monto >= 0),
    nota         text
);

CREATE TABLE distribucion_ganancia (
    id        smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id  smallint NOT NULL REFERENCES socio(id),
    periodo   text NOT NULL,
    monto     numeric(14,2) NOT NULL CHECK (monto >= 0),
    UNIQUE (socio_id, periodo)
);

-- ---------------------------------------------------------------------------
-- 9. Encuestas
-- ---------------------------------------------------------------------------

CREATE TABLE encuesta (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       text NOT NULL,
    tipo         text NOT NULL CHECK (tipo IN ('preferencia', 'satisfaccion')),
    fecha_desde  date,
    fecha_hasta  date,
    respuestas   smallint NOT NULL CHECK (respuestas > 0),
    CHECK (fecha_hasta IS NULL OR fecha_desde IS NULL OR fecha_hasta >= fecha_desde)
);

CREATE TABLE encuesta_pregunta (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encuesta_id smallint NOT NULL REFERENCES encuesta(id) ON DELETE CASCADE,
    codigo      text NOT NULL,
    texto       text NOT NULL,
    tipo        text NOT NULL CHECK (tipo IN ('unica', 'multiple', 'escala', 'abierta')),
    orden       smallint NOT NULL DEFAULT 0,
    UNIQUE (encuesta_id, codigo)
);

CREATE TABLE encuesta_opcion (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id  smallint NOT NULL REFERENCES encuesta_pregunta(id) ON DELETE CASCADE,
    etiqueta     text NOT NULL,
    orden        smallint NOT NULL DEFAULT 0,
    UNIQUE (pregunta_id, etiqueta)
);

CREATE TABLE encuesta_resultado (
    id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opcion_id  smallint NOT NULL UNIQUE REFERENCES encuesta_opcion(id) ON DELETE CASCADE,
    cantidad   smallint NOT NULL CHECK (cantidad >= 0)
);

CREATE TABLE encuesta_indicador (
    id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id  smallint NOT NULL REFERENCES encuesta_pregunta(id) ON DELETE CASCADE,
    nombre       text NOT NULL,
    valor        numeric(10,2) NOT NULL,
    UNIQUE (pregunta_id, nombre)
);

-- ---------------------------------------------------------------------------
-- 10. Índices de apoyo
-- ---------------------------------------------------------------------------

CREATE INDEX ix_aporte_capital_socio       ON aporte_capital (socio_id);
CREATE INDEX ix_socio_rol_rol              ON socio_rol (rol_id);
CREATE INDEX ix_producto_categoria         ON producto (categoria_id);
CREATE INDEX ix_producto_precio_producto   ON producto_precio (producto_id);
CREATE INDEX ix_producto_costo_producto    ON producto_costo (producto_id);
CREATE INDEX ix_proveedor_insumo_proveedor ON proveedor_insumo (proveedor_id);
CREATE INDEX ix_proveedor_insumo_insumo    ON proveedor_insumo (insumo_id);
CREATE INDEX ix_compra_proveedor           ON compra (proveedor_id);
CREATE INDEX ix_compra_fecha               ON compra (fecha);
CREATE INDEX ix_detalle_compra_compra      ON detalle_compra (compra_id);
CREATE INDEX ix_lote_produccion_jornada    ON lote_produccion (jornada_id);
CREATE INDEX ix_lote_produccion_producto   ON lote_produccion (producto_id);
CREATE INDEX ix_venta_fecha                ON venta (fecha);
CREATE INDEX ix_venta_canal                ON venta (canal);
CREATE INDEX ix_venta_evento               ON venta (evento_id);
CREATE INDEX ix_detalle_venta_venta        ON detalle_venta (venta_id);
CREATE INDEX ix_detalle_venta_producto     ON detalle_venta (producto_id);
CREATE INDEX ix_distribucion_socio         ON distribucion_ganancia (socio_id);
CREATE INDEX ix_encuesta_pregunta_encuesta ON encuesta_pregunta (encuesta_id);
CREATE INDEX ix_encuesta_opcion_pregunta   ON encuesta_opcion (pregunta_id);
CREATE INDEX ix_encuesta_indicador_pregunta ON encuesta_indicador (pregunta_id);

COMMIT;
